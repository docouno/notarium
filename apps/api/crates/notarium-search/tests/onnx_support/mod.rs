pub fn library() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../../../.artifacts/onnxruntime/current/libonnxruntime.so")
        .canonicalize()
        .expect("run make setup to prepare the pinned ONNX Runtime fixture")
}

pub struct ModelFiles(pub PathBuf);

impl ModelFiles {
    pub fn new() -> Self {
        let mut entropy = [0; 16];
        getrandom::fill(&mut entropy).unwrap();
        Self(std::env::temp_dir().join(format!("notarium-onnx-{}", hex::encode(entropy))))
    }

    pub fn install(&self, model: &ModelProfileId, slow: bool) {
        let graph = if slow {
            INTERRUPTIBLE_MODEL
        } else {
            EMBEDDING_MODEL
        };
        self.install_graph(model, graph);
    }

    #[allow(dead_code)]
    pub fn install_with_type_ids(&self, model: &ModelProfileId) {
        self.install_graph(model, EMBEDDING_MODEL_WITH_TYPE_IDS);
    }

    #[allow(dead_code)]
    pub fn install_pooled_2d(&self, model: &ModelProfileId) {
        self.install_graph(model, POOLED_2D_MODEL);
    }

    #[allow(dead_code)]
    pub fn install_conditional_slow(&self, model: &ModelProfileId) {
        self.install_graph(model, CONDITIONAL_INTERRUPTIBLE_MODEL);
    }

    fn install_graph(&self, model: &ModelProfileId, graph_hex: &str) {
        let profile = self.0.join(model.as_str());
        fs::create_dir_all(&profile).unwrap();
        fs::write(profile.join("model.onnx"), hex::decode(graph_hex).unwrap()).unwrap();
        fs::write(
            profile.join("tokenizer.json"),
            r###"{
            "pre_tokenizer":{"type":"WhitespaceSplit"},
            "model":{"type":"WordPiece","vocab":{"[UNK]":0,"red":1,"blue":2,"[PAD]":3,"##dish":4,"zero":64},
            "unk_token":"[UNK]","continuing_subword_prefix":"##","max_input_chars_per_word":100}
        }"###,
        )
        .unwrap();
    }
}

impl Drop for ModelFiles {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.0);
    }
}
